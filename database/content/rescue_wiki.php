## Einsätze in der Nähe von Fort Zancudo
- Der Zancudo River und der Lago Zancudo grenzen direkt an das Gelände. Vermisste, Boote oder Abgetriebene können ins Sperrgebiet geraten.
- Der Luftraum über Fort Zancudo ist gesperrt. Hubschrauber und Drohnen fliegen ihn **nicht** ohne Freigabe an, siehe [[Drohnen und Wärmebild]].

## Ablauf bei Freigabebedarf
1. Einsatzleitung meldet über die Leitstelle den Bedarf: Grund, Bereich, Kräfte, Dauer.
2. Leitstelle stellt Kontakt zur Wache von Fort Zancudo her.
3. Erst nach Bestätigung der Freigabe (mit Name des Freigebenden und Uhrzeit) wird das Gebiet betreten oder überflogen.
4. Kräfte halten sich an die zugewiesenen Wege und Bereiche und folgen Anweisungen des militärischen Personals.
5. Abmeldung nach Verlassen des Gebiets.

## Weitere Sperrgebiete und Schutzbereiche
- **LSIA** und **Sandy Shores Airfield**: Kontrollzonen, An- und Abflug mit der Flugsicherung abstimmen.
- **Land Act Dam**: Unterwasserbereich nur nach Freigabe des Betreibers, siehe [[Strömungsrettung Cassidy Creek und Zancudo River]].
- **Port of Los Santos**: Hafensicherheitsbereich, Abstimmung mit dem Hafenmeister, siehe [[SOP Hafen und Hafenbecken Port of Los Santos]].
- Privatgelände und Ranches im Great Chaparral: Zugang mit Eigentümer oder Polizei.

## Dokumentation
Freigaben werden mit Uhrzeit und Namen im **Einsatzbericht Spezialrettung** bzw. im **Flugbericht** vermerkt, siehe [[Einsatzdokumentation der TAS]].
