Katecholamin, Sympathomimetikum. Wirkt an Alpha- und Beta-Rezeptoren: Gefäßverengung, Steigerung von Herzfrequenz und Kontraktionskraft, Erweiterung der Bronchien. Stabilisiert Mastzellen bei Anaphylaxie.

