- Bei Vernehmungen anwesend sein. Der Mandant darf vor jeder Antwort mit euch sprechen.

## Rechte des Festgenommenen
- Recht zu **schweigen** und keine Angaben zur Sache zu machen.
- Recht auf einen **Rechtsbeistand**.
- Recht auf **medizinische Versorgung**.
- Recht, über den Tatvorwurf informiert zu werden.

Werden diese Rechte missachtet, notiert ihr Uhrzeit, Namen bzw. Dienstnummern der Beamten und den genauen Ablauf. Solche Verstöße können später ein **Beweisverwertungsverbot** begründen, siehe [[Beweisanträge]].

## Ruhig und professionell bleiben
Beamte auf der Wache machen ihren Job. Lautes Auftreten hilft dem Mandanten nicht. Sachlich bleiben, Rechte einfordern, alles dokumentieren. Zur Zusammenarbeit siehe [[Zusammenarbeit mit der Polizei]].

