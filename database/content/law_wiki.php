Anwältinnen und Anwälte üben einen **freien Beruf** aus und sind unabhängige Organe der Rechtspflege. Daraus ergeben sich besondere Pflichten, deren Verletzung bis zum Verlust der Zulassung führen kann.

## Die Grundpflichten
1. **Unabhängigkeit**: Keine Bindungen, die die Vertretung des Mandanten beeinträchtigen – weder an Behörden noch an kriminelle Organisationen.
2. **Verschwiegenheit**: siehe [[Verschwiegenheit]].
3. **Verbot widerstreitender Interessen**: siehe [[Interessenkonflikt-Prüfung]].
4. **Sachlichkeit**: Keine bewusste Verbreitung von Unwahrheiten, keine herabsetzenden Äußerungen ohne Anlass.
5. **Sorgfalt**: Fristen wahren, Akten ordentlich führen, siehe [[Fristenkontrolle]] und [[Aktenführung]].
6. **Fortbildung**: Gesetze unter **Gesetze** im Portal kennen und Änderungen verfolgen.

## Wahrheitspflicht
Die Verteidigung darf das Gericht **nicht belügen**. Sie muss aber auch nicht alles sagen, was sie weiß. Erlaubt ist, auf Beweislücken hinzuweisen und Freispruch zu beantragen, auch wenn der Mandant die Tat eingeräumt hat. Nicht erlaubt ist, Zeugen zu einer Falschaussage zu bewegen oder gefälschte Beweise vorzulegen.

## Umgang mit Mandantengeld
Fremdgeld (z. B. eine eingezogene Forderung) wird getrennt vom Kanzleivermögen geführt und unverzüglich an den Mandanten weitergeleitet, siehe [[Honorar und Abrechnung]].

## Werbung
Sachliche Information über Kanzlei und Schwerpunkte ist erlaubt. Unzulässig sind Erfolgsversprechen und aufdringliche Werbung, etwa das Ansprechen von Unfallopfern am Unfallort.

## Konsequenzen bei Verstößen
Je nach Schwere und Regelung des Servers: Rüge durch die Kanzleileitung, Hinweis des Gerichts, Ausschluss aus einem Verfahren, Entzug der Zulassung. Verstöße, die zugleich Straftaten sind (z. B. Strafvereitelung, Beweismittelunterdrückung), werden zusätzlich strafrechtlich verfolgt.

