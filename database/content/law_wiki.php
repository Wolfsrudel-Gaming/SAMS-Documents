Eine Kanzlei darf nicht **widerstreitende Interessen** vertreten. Wer in derselben Sache beide Seiten berät, verrät zwangsläufig eine davon. Die Prüfung auf Interessenkonflikte erfolgt deshalb **vor** dem eigentlichen Erstgespräch.

## Typische Konfliktfälle
- Die Kanzlei vertritt bereits den **Unfallgegner**, den **Geschädigten** oder die **Gegenpartei** eines Zivilstreits.
- Zwei **Mitbeschuldigte** derselben Tat wollen sich von derselben Kanzlei verteidigen lassen. Schon wenn einer den anderen belasten könnte, ist eine gemeinsame Verteidigung ausgeschlossen.
- Eine Anwältin war früher in derselben Sache auf der anderen Seite tätig, etwa als Mitarbeiterin der Staatsanwaltschaft.
- Persönliche Nähe: Die Anwältin ist mit dem Opfer verwandt oder befreundet.

## So wird geprüft
1. Namen aller Beteiligten erfragen: Mandant, Gegner, Zeugen, Mitbeschuldigte.
2. In den **Mandantenakten** der Kanzlei nach diesen Namen suchen, siehe [[Mandantenakten im Portal]].
3. Bei Treffern die Kanzleileitung einbinden. Sie entscheidet, ob ein Konflikt besteht.
4. Ergebnis in der neuen Akte vermerken: „Konfliktprüfung durchgeführt am …, ohne Befund“.

## Was tun bei einem Konflikt?
- Das Mandat wird **abgelehnt**, bevor vertrauliche Informationen ausgetauscht werden.
- Ergibt sich der Konflikt erst später, muss in der Regel **das neue Mandat** niedergelegt werden – im Zweifel auch beide.
- Dem Mandanten wird nur gesagt, dass die Kanzlei aus berufsrechtlichen Gründen nicht tätig werden kann. Gründe, die Rückschlüsse auf andere Mandanten zulassen, werden **nicht** genannt (siehe [[Verschwiegenheit]]).

## Im Rollenspiel
Gerade auf einem Server mit wenigen Kanzleien kommt es oft vor, dass beide Parteien zur selben Kanzlei wollen. Dann ist es fair und realistisch, auf eine andere Kanzlei im [[Anwaltsverzeichnis]] zu verweisen oder eine Pflichtverteidigung über das Gericht anzuregen, siehe [[Pflichtverteidigung]].
