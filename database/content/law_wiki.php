Fristen sind das größte Haftungsrisiko jeder Kanzlei. Eine versäumte Einspruchs- oder Rechtsmittelfrist kann ein Urteil **rechtskräftig** machen, obwohl es angreifbar gewesen wäre.

## Wichtige Fristarten
| Frist | Beispiel | Folge bei Versäumnis |
|---|---|---|
| **Einspruchsfrist** | gegen einen Strafbefehl | Strafbefehl wird rechtskräftig, siehe [[Einspruch gegen Strafbefehl]] |
| **Rechtsmittelfrist** | Berufung oder Revision | Urteil wird rechtskräftig, siehe [[Berufung und Revision]] |
| **Widerspruchsfrist** | gegen einen Behördenbescheid | Bescheid wird bestandskräftig, siehe [[Widerspruch gegen Bescheide]] |
| **Gerichtliche Frist** | Stellungnahme, Klageerwiderung | Vortrag kann als verspätet zurückgewiesen werden |

Die konkreten Fristlängen legt euer Server bzw. das Gericht fest. Steht keine Frist in der Entscheidung, fragt beim Superior Court nach, statt eine Frist zu vermuten.

## Das Vier-Augen-Prinzip
1. **Eingang prüfen**: Jedes Schreiben von Gericht, Staatsanwaltschaft oder Behörde wird sofort auf Fristen gelesen.
2. **Frist notieren** mit Ablaufdatum **und** einer Vorfrist (einige Tage vorher).
3. **Frist im Portal eintragen**, sodass sie im [[Gerichtskalender]] erscheint.
4. **Gegenzeichnung**: Eine zweite Person prüft die Berechnung.
5. **Erledigung vermerken**, wenn der Schriftsatz eingereicht wurde, mit Uhrzeit.

## Regeln
- Eine Frist wird **niemals** nur im Kopf oder auf einem Zettel geführt.
- Schriftsätze werden **nicht am letzten Tag** eingereicht, wenn es sich vermeiden lässt.
- Bei Urlaub oder Abwesenheit wird eine Vertretung bestimmt, die die Fristen übernimmt.
- Fristverlängerungen müssen **vor Ablauf** schriftlich beim Gericht beantragt werden.

## Fristversäumnis – was nun?
Sofort die Kanzleileitung informieren und prüfen, ob ein Antrag auf Wiedereinsetzung oder Nachholung möglich ist. Den Mandanten ehrlich informieren – Vertuschen verschlimmert jede Lage.

*Merke:* Keine Frist ohne Eintrag, kein Eintrag ohne Gegenzeichnung.
