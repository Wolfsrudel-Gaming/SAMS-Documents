1. Wo befindet sich der Mandant (Wache Mission Row, Sheriff-Station Sandy Shores, Paleto Bay …)?
2. Was wird ihm vorgeworfen, soweit bekannt?
3. Ist er verletzt? Dann sofort auf ärztliche Versorgung durch SAMS bestehen.
