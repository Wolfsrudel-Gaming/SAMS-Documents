Das **Mandat** ist der Auftrag eines Mandanten an die Kanzlei. Mit der Annahme übernimmt die Kanzlei Verantwortung – und Haftung. Deshalb wird kein Mandat „nebenbei“ angenommen.

## Ablauf der Mandatsannahme
1. **Erstkontakt** aufnehmen: Name, Erreichbarkeit, kurze Schilderung des Anliegens, Dringlichkeit (Festnahme? laufende Frist?).
2. **Interessenkonflikt prüfen**, bevor Details besprochen werden, siehe [[Interessenkonflikt-Prüfung]].
3. **Erstgespräch** führen und Sachverhalt aufnehmen, siehe [[Erstgespräch mit dem Mandanten]].
4. **Honorar** besprechen und schriftlich festhalten, siehe [[Honorar und Abrechnung]].
5. **Vollmacht** erteilen lassen, siehe [[Vollmacht]].
6. **Akte anlegen** und Fristen eintragen, siehe [[Mandantenakten im Portal]] und [[Fristenkontrolle]].

## Wann ein Mandat abgelehnt wird
- Es besteht ein **Interessenkonflikt**, etwa weil die Kanzlei bereits die Gegenseite vertritt.
- Der Mandant verlangt **rechtswidriges Handeln**, zum Beispiel das Verstecken von Beweismitteln oder eine Falschaussage.
- Die Kanzlei hat **keine Kapazität**, um eine anstehende Frist sicher zu wahren.
- Das Anliegen liegt außerhalb der eigenen Fachkenntnis und es ist keine qualifizierte Kollegin verfügbar.

Eine Ablehnung erfolgt **unverzüglich** und mit dem Hinweis auf laufende Fristen, damit der Mandant rechtzeitig anderweitig Hilfe suchen kann. Hilfreich ist ein Verweis auf das [[Anwaltsverzeichnis]].

## Mandatsbeendigung
Ein Mandat endet mit dem Abschluss der Angelegenheit, durch Kündigung des Mandanten oder durch Niederlegung der Kanzlei. Eine Niederlegung darf **nicht zur Unzeit** erfolgen – also nicht am Tag vor der Hauptverhandlung ohne Not. Gericht und Staatsanwaltschaft werden schriftlich informiert, die Vollmacht wird im Portal beendet.

*Merke:* Erst Konfliktprüfung, dann Sachverhalt, dann Vollmacht.
