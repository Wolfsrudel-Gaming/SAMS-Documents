    ['title' => 'Verschwiegenheit', 'category' => 'Kanzleiorganisation', 'content' => <<<'MD'
Die **anwaltliche Verschwiegenheit** ist die Grundlage des Vertrauens zwischen Mandant und Kanzlei. Nur wer offen sprechen kann, kann gut verteidigt werden.

## Was fällt unter die Verschwiegenheit?
- **Alles**, was im Rahmen des Mandats bekannt wird: Aussagen des Mandanten, Unterlagen, Gesundheitsdaten, Finanzen.
- Bereits die **Tatsache**, dass jemand Mandant der Kanzlei ist.
- Informationen über andere Mandanten, die man zufällig erfährt.

Die Verschwiegenheit gilt gegenüber **jedermann**: Polizei, Staatsanwaltschaft, Presse, Familie, Freunde und auch gegenüber Kolleginnen anderer Kanzleien.

## Zeugnisverweigerungsrecht
Anwältinnen und Anwälte dürfen vor Gericht und gegenüber der Polizei über das, was ihnen als Rechtsbeistand anvertraut wurde, das **Zeugnis verweigern**. Auch Kanzleiunterlagen über das Mandat sind grundsätzlich vor Beschlagnahme geschützt. Wird die Kanzlei durchsucht, verlangt ihr den richterlichen Beschluss und protestiert schriftlich gegen die Mitnahme geschützter Unterlagen.

## Ausnahmen
- Der Mandant **entbindet** die Kanzlei ausdrücklich von der Verschwiegenheit.
- Die Kanzlei muss sich gegen Vorwürfe des Mandanten verteidigen, etwa im Honorarstreit – dann nur so weit wie nötig.
- Zur Abwendung einer **unmittelbar bevorstehenden schweren Straftat** gegen Leib und Leben. Das ist eine eng begrenzte Ausnahme und wird mit der Kanzleileitung abgestimmt.

## Praktische Regeln
- Mandate nicht in der Öffentlichkeit, im Funk oder vor Unbeteiligten besprechen.
- Haftbesuche nur in einem Raum ohne Mithörer, siehe [[Haftbesuch]].
- Akten im Portal nur für Berechtigte freigeben, siehe [[Mandantenakten im Portal]].
- Medizinische Unterlagen nur mit [[Schweigepflichtentbindung und SAMS]] anfordern.

*Merke:* Was der Mandant der Kanzlei sagt, bleibt in der Kanzlei.
