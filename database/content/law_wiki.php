## Die Frist
Der Einspruch muss **innerhalb der Einspruchsfrist** eingelegt werden, die im Strafbefehl genannt ist. Sie beginnt mit der Zustellung. Sofort eintragen, siehe [[Fristenkontrolle]].

## Wann lohnt sich ein Einspruch?
